def _selected_groups(args) -> tuple[str, ...]:
    if args.all:
        return ALL_GROUPS
    sel = [g for g in ALL_GROUPS if getattr(args, g.replace("-", "_"))]
    return tuple(sel)


def _plan(groups, *, mirror, suite, components, index=None) -> dict:
    """Resolve filenames + the planned member paths for ``groups`` (the --list view)."""
    pkgs = packages_for_groups(groups)
    filenames = resolve_filenames(
        pkgs, mirror=mirror, suite=suite, arch=ARCH, components=components, index=index
    ) if pkgs else {}
    planned: list[str] = []
    if "ca" in groups:
        planned.append("./" + CA_BUNDLE_PATH)
    if "mime" in groups:
        planned.append("./" + MIME_DIR + "/** (compiled via update-mime-database)")
    if "icons" in groups:
        planned += ["./" + HICOLOR_INDEX, "./" + ADWAITA_INDEX,
                    "./" + ICON_DIR + "/Adwaita/** (minus icon-theme.cache)"]
    if "machine-id" in groups:
        planned += ["./" + p for p in MACHINE_ID_PATHS] + ["./" + DBUS_SESSION_CONF_PATH]
    if "locale" in groups:
        planned.append("./" + LOCALE_PREFIX + "**")
    return {
        "groups": list(groups),
        "packages": pkgs,
        "filenames": filenames,
        "planned_members": planned,
        "update_mime_database": shutil.which("update-mime-database") or "(absent)",
        "gtk_update_icon_cache": shutil.which("gtk-update-icon-cache") or "(absent)",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="build_common_data_overlay",
        description="Build the one-shot COMMON-DATA overlay (CA bundle + MIME db + "
        "icon indices + machine-id/dbus stub + C.UTF-8 locale) that most GUI+network "
        "glibc apps need but the DT_NEEDED-only deb closure drops.",
    )
    parser.add_argument("--out", help="output stage tar (e.g. /tmp/common-data-stage.tar)")
    # per-group flags
    parser.add_argument("--ca", action="store_true",
                        help="ship /etc/ssl/certs/ca-certificates.crt (Mozilla CA bundle)")
    parser.add_argument("--mime", action="store_true",
                        help="ship /usr/share/mime/** (freedesktop MIME db, compiled)")
    parser.add_argument("--icons", action="store_true",
                        help="ship hicolor + Adwaita index.theme (+ Adwaita payload)")
    parser.add_argument("--machine-id", dest="machine_id", action="store_true",
                        help="ship /etc/machine-id + dbus machine-id + session.conf stub")
    parser.add_argument("--locale", action="store_true",
                        help="ship /usr/lib/locale/C.utf8/** (compiled C.UTF-8 locale)")
    parser.add_argument("--all", action="store_true", help="select every group")
    parser.add_argument("--suite", default=SUITE)
    parser.add_argument("--mirror", default=MIRROR)
    parser.add_argument("--component", action="append", dest="components",
                        help="repo component (repeatable; default main)")
    parser.add_argument("--cache", default="/tmp/deb-cache-ubuntu")
    parser.add_argument("--list", "--dry-run", action="store_true", dest="dry_run",
                        help="resolve each group's .deb + print the planned members "
                        "WITHOUT downloading/packing")
    parser.add_argument("--json", action="store_true", help="machine-readable output")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args(argv)

    if args.selftest:
        return _selftest()

    components = tuple(args.components) if args.components else COMPONENTS
    groups = _selected_groups(args)
    if not groups:
        # Sensible default for --list with no group flags: show everything.
        groups = ALL_GROUPS

    if args.dry_run:
        info = _plan(groups, mirror=args.mirror, suite=args.suite,
                     components=components)
        if args.json:
            print(json.dumps(info, indent=2))
        else:
            print(f"common-data overlay plan ({args.suite}/{'+'.join(components)}):")
            print(f"  groups: {', '.join(info['groups'])}")
            for pkg in info["packages"]:
                print(f"  deb {pkg}: {info['filenames'].get(pkg)}")
            print(f"  update-mime-database: {info['update_mime_database']}")
            print(f"  gtk-update-icon-cache: {info['gtk_update_icon_cache']}")
            print("  planned members:")
            for m in info["planned_members"]:
                print(f"    {m}")
        return 0

    if not args.out:
        parser.error("--out is required for a full build (or use --list / --selftest)")

    res = build_common_data_overlay(
        args.out, groups, mirror=args.mirror, suite=args.suite, arch=ARCH,
        components=components, cache_dir=args.cache,
    )
    if args.json:
        print(json.dumps(res.as_dict(), indent=2))
    else:
        print(f"built {res.out_tar}")
        print(f"  groups: {', '.join(res.groups)}")
        print(f"  files in overlay: {res.file_count}")
        if "ca" in res.groups:
            print(f"  CA bundle: {res.ca_cert_count} certs, "
                  f"{round(res.ca_bundle_bytes / 1024, 1)} KiB")
        if "mime" in res.groups:
            print(f"  MIME db: {res.mime_file_count} files "
                  f"(compiled={res.mime_compiled})")
        if "icons" in res.groups:
            print(f"  icons: {res.icon_file_count} files "
                  f"(binary cache shipped={res.icon_cache_shipped})")
        if "locale" in res.groups:
            print(f"  locale C.utf8: {res.locale_file_count} files")
        if res.debs:
            print(f"  source debs: {', '.join(res.debs)}")
        if res.notes:
            print("  notes:")
            for n in res.notes:
                print(f"    - {n}")
    return 0


