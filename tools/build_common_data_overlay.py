@dataclass
class CommonDataResult:
    out_tar: str
    groups: tuple[str, ...] = ()
    members: tuple[str, ...] = ()
    file_count: int = 0
    ca_cert_count: int = 0
    ca_bundle_bytes: int = 0
    mime_file_count: int = 0
    mime_compiled: bool = False           # did update-mime-database run?
    icon_file_count: int = 0
    icon_cache_shipped: bool = False      # binary icon-theme.cache (postinst tool)
    locale_file_count: int = 0
    debs: tuple[str, ...] = ()
    notes: tuple[str, ...] = ()

    def as_dict(self) -> dict:
        return {
            "out_tar": self.out_tar,
            "groups": list(self.groups),
            "members": list(self.members),
            "file_count": self.file_count,
            "ca_cert_count": self.ca_cert_count,
            "ca_bundle_bytes": self.ca_bundle_bytes,
            "ca_bundle_kib": round(self.ca_bundle_bytes / 1024, 1),
            "mime_file_count": self.mime_file_count,
            "mime_compiled": self.mime_compiled,
            "icon_file_count": self.icon_file_count,
            "icon_cache_shipped": self.icon_cache_shipped,
            "locale_file_count": self.locale_file_count,
            "debs": list(self.debs),
            "notes": list(self.notes),
        }


# --------------------------------------------------------------------------- #
# tar helpers (§5-E ./-rooted, mtime=0, deterministic)
# --------------------------------------------------------------------------- #

def _member_name(rel: str) -> str:
    return "./" + rel.strip("/")


def _add_dir(tar: tarfile.TarFile, rel: str, mode: int = 0o755) -> None:
    ti = tarfile.TarInfo(_member_name(rel))
    ti.type = tarfile.DIRTYPE
    ti.mode = mode
    ti.mtime = 0
    tar.addfile(ti)


def _add_file(tar: tarfile.TarFile, rel: str, data: bytes, mode: int = 0o644) -> None:
    ti = tarfile.TarInfo(_member_name(rel))
    ti.size = len(data)
    ti.mode = mode
    ti.mtime = 0
    ti.type = tarfile.REGTYPE
    tar.addfile(ti, io.BytesIO(data))


def _norm(rel: str) -> str:
    """Strip leading ./ and / from a tar member name -> rootfs-relative path."""
    while rel.startswith("./"):
        rel = rel[2:]
    return rel.lstrip("/")


# --------------------------------------------------------------------------- #
# Filename resolution
# --------------------------------------------------------------------------- #

def resolve_filenames(
    packages,
    *,
    mirror: str = MIRROR,
    suite: str = SUITE,
    arch: str = ARCH,
    components=COMPONENTS,
    index: dict[str, dict] | None = None,
) -> dict[str, str]:
    """Resolve each package name to its .deb ``Filename`` in the noble index.

    NETWORK unless ``index`` is supplied (offline/selftest). Raises if a requested
    package is absent from the index."""
    if index is None:
        index = parse_packages(
            fetch_packages_index(mirror, suite, arch, components=components)
        )
    out: dict[str, str] = {}
    for pkg in packages:
        fields = index.get(pkg, {})
        filename = fields.get("Filename")
        if not filename:
            raise RuntimeError(
                f"{pkg} not found in {suite}/{'+'.join(components)} index"
            )
        out[pkg] = filename
    return out


def packages_for_groups(groups) -> list[str]:
    """The set of noble packages a group selection needs (deduped, ordered)."""
    pkgs: list[str] = []
    for g in groups:
        if g == "icons":
            for p in ICON_PACKAGES:
                if p not in pkgs:
                    pkgs.append(p)
        elif g in GROUP_PACKAGES:
            p = GROUP_PACKAGES[g]
            if p not in pkgs:
                pkgs.append(p)
        # machine-id needs no package
    return pkgs


# --------------------------------------------------------------------------- #
# ca group — assemble the CA bundle from the ca-certificates .deb
# --------------------------------------------------------------------------- #

def assemble_ca_bundle(deb: Path) -> tuple[bytes, int]:
    """Concatenate every PEM CA in the ca-certificates .deb into one bundle.

    Reproduces ``update-ca-certificates`` with the default (all-enabled) config:
    pulls every ``usr/share/ca-certificates/**/*.crt`` regular-file member from the
    .deb data.tar (in-memory; tolerant of absolute-symlink members elsewhere),
    keeps only PEM-bearing files, and concatenates them sorted-by-path
    (deterministic), each cert newline-terminated. Returns ``(bundle, cert_count)``.
    """
    raw = _decompress_data_tar(deb)
    pems: list[tuple[str, bytes]] = []
    with tarfile.open(fileobj=io.BytesIO(raw), mode="r:") as t:
        for m in t.getmembers():
            rel = _norm(m.name)
            if rel.startswith(CA_SRC_PREFIX) and rel.endswith(".crt") and m.isfile():
                fh = t.extractfile(m)
                if fh is None:
                    continue
                body = fh.read()
                if b"-----BEGIN CERTIFICATE-----" not in body:
                    continue
                pems.append((rel, body))
    pems.sort(key=lambda kv: kv[0])
    chunks = [b if b.endswith(b"\n") else b + b"\n" for _, b in pems]
    return b"".join(chunks), len(pems)


# --------------------------------------------------------------------------- #
# mime group — extract the source XML, compile via update-mime-database
# --------------------------------------------------------------------------- #

def _extract_prefix(deb: Path, prefix: str, dest_root: Path) -> list[str]:
    """Extract every regular-file member under ``prefix`` of a .deb to dest_root.

    In-memory data.tar read (no extract-to-disk for the whole archive, so an
    absolute-symlink member elsewhere can't abort us). Returns the sorted list of
    rootfs-relative paths written. ``prefix`` is matched on the normalised
    (leading-./-stripped) member name."""
    raw = _decompress_data_tar(deb)
    written: list[str] = []
    with tarfile.open(fileobj=io.BytesIO(raw), mode="r:") as t:
        for m in t.getmembers():
            rel = _norm(m.name)
            if not rel.startswith(prefix) or not m.isfile():
                continue
            fh = t.extractfile(m)
            if fh is None:
                continue
            dst = dest_root / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(fh.read())
            written.append(rel)
    written.sort()
    return written


def build_mime_tree(deb: Path, work: Path) -> tuple[Path, bool, list[str]]:
    """Stage the source MIME XML, then compile the binary database if possible.

    Returns ``(mime_root, compiled, notes)`` where ``mime_root`` is the directory
    whose ``usr/share/mime`` subtree should be packed. ``compiled`` is True iff
    ``update-mime-database`` ran (and thus ``mime.cache``/``globs2``/``magic``/…
    were generated); when the tool is absent only the source XML is staged and a
    note explains the degradation."""
    notes: list[str] = []
    _extract_prefix(deb, MIME_DIR + "/", work)
    mime_share = work / MIME_DIR
    tool = shutil.which("update-mime-database")
    compiled = False
    if tool is not None and mime_share.is_dir():
        try:
            subprocess.run(
                [tool, str(mime_share)],
                check=True, capture_output=True,
            )
            compiled = (mime_share / "mime.cache").is_file()
        except subprocess.CalledProcessError as exc:  # pragma: no cover - host tool
            notes.append(
                f"update-mime-database failed (rc={exc.returncode}); shipping source "
                "XML only — file-type detection will be degraded on device"
            )
        if not compiled and not notes:
            notes.append(
                "update-mime-database ran but produced no mime.cache; shipping source "
                "XML only"
            )
    else:
        notes.append(
            "update-mime-database not on PATH; mime group ships the source XML only "
            "(no compiled mime.cache/globs2/magic) — run the builder on a host with "
            "shared-mime-info installed, or compile on device"
        )
    return work, compiled, notes


# --------------------------------------------------------------------------- #
# icons group — index.theme (+ Adwaita payload) from the theme .debs
# --------------------------------------------------------------------------- #

def _pack_deb_prefix(
    tar: tarfile.TarFile, deb: Path, prefix: str, *, skip=()
) -> list[str]:
    """Copy every regular-file member of ``deb`` under ``prefix`` into ``tar`` at
    its rootfs-absolute (./-rooted) path, preserving mode bits. ``skip`` is an
    iterable of member-name SUFFIXES to drop (e.g. a postinst-only cache). Returns
    the sorted rootfs-relative paths packed."""
    raw = _decompress_data_tar(deb)
    packed: list[str] = []
    skip = tuple(skip)
    with tarfile.open(fileobj=io.BytesIO(raw), mode="r:") as t:
        for m in t.getmembers():
            rel = _norm(m.name)
            if not rel.startswith(prefix) or not m.isfile():
                continue
            if skip and rel.endswith(skip):
                continue
            fh = t.extractfile(m)
            if fh is None:
                continue
            data = fh.read()
            mode = (m.mode & 0o7777) or 0o644
            _add_file(tar, rel, data, mode=mode)
            packed.append(rel)
    packed.sort()
    return packed


# --------------------------------------------------------------------------- #
# Full build
# --------------------------------------------------------------------------- #

def build_common_data_overlay(
    out_tar: str | Path,
    groups,
    *,
    mirror: str = MIRROR,
    suite: str = SUITE,
    arch: str = ARCH,
    components=COMPONENTS,
    cache_dir: str | Path | None = None,
    index: dict[str, dict] | None = None,
    # offline/selftest injection: skip the network for the ca group.
    ca_bundle: bytes | None = None,
    ca_cert_count: int | None = None,
) -> CommonDataResult:
    """Pack the selected groups into one §5-E ``common-data-stage.tar``.

    NETWORK PATH unless every selected group's data is injected. Resolves each
    group's noble .deb, assembles/extracts/synthesizes its data, and writes it at
    the canonical rootfs-absolute paths. ``machine-id`` is synthesized (no deb).
    """
    groups = tuple(dict.fromkeys(groups))  # dedupe, keep order
    unknown = [g for g in groups if g not in ALL_GROUPS]
    if unknown:
        raise ValueError(f"unknown group(s): {unknown}; choose from {ALL_GROUPS}")

    out_tar = Path(out_tar)
    out_tar.parent.mkdir(parents=True, exist_ok=True)
    cache = Path(cache_dir) if cache_dir is not None else Path("/tmp/deb-cache-ubuntu")

    # Resolve the .deb Filenames we will need (skip when fully injected offline).
    need_net = not (set(groups) <= {"machine-id"} or
                    (set(groups) <= {"ca", "machine-id"} and ca_bundle is not None))
    filenames: dict[str, str] = {}
    if need_net or (("ca" in groups) and ca_bundle is None):
        filenames = resolve_filenames(
            packages_for_groups(groups),
            mirror=mirror, suite=suite, arch=arch, components=components, index=index,
        )

    members: list[str] = []
    debs: list[str] = []
    notes: list[str] = []
    res = CommonDataResult(out_tar=str(out_tar), groups=groups)

    # A scratch dir for the mime compile step (cleaned at the end).
    work = Path(tempfile.mkdtemp(prefix="alr-common-data-"))
    try:
        with tarfile.open(out_tar, "w") as tar:
            # --- ca ------------------------------------------------------- #
            if "ca" in groups:
                if ca_bundle is None:
                    fn = filenames["ca-certificates"]
                    deb = _download_deb(mirror, fn, cache)
                    debs.append(Path(fn).name)
                    ca_bundle, ca_cert_count = assemble_ca_bundle(deb)
                elif ca_cert_count is None:
                    ca_cert_count = ca_bundle.count(b"-----BEGIN CERTIFICATE-----")
                for d in ("etc", "etc/ssl", "etc/ssl/certs"):
                    _add_dir(tar, d)
                _add_file(tar, CA_BUNDLE_PATH, ca_bundle)
                members.append("./" + CA_BUNDLE_PATH)
                res.ca_cert_count = ca_cert_count or 0
                res.ca_bundle_bytes = len(ca_bundle)

            # --- mime ----------------------------------------------------- #
            if "mime" in groups:
                fn = filenames["shared-mime-info"]
                deb = _download_deb(mirror, fn, cache)
                debs.append(Path(fn).name)
                mime_root, compiled, mnotes = build_mime_tree(deb, work)
                notes.extend(mnotes)
                res.mime_compiled = compiled
                mime_share = mime_root / MIME_DIR
                count = 0
                for p in sorted(mime_share.rglob("*")):
                    if p.is_file():
                        rel = p.relative_to(mime_root).as_posix()
                        _add_file(tar, rel, p.read_bytes())
                        members.append("./" + rel)
                        count += 1
                res.mime_file_count = count

            # --- icons ---------------------------------------------------- #
            if "icons" in groups:
                count = 0
                # hicolor: just the base index.theme (it has no icons of its own).
                fn = filenames["hicolor-icon-theme"]
                deb = _download_deb(mirror, fn, cache)
                debs.append(Path(fn).name)
                packed = _pack_deb_prefix(
                    tar, deb, "usr/share/icons/hicolor/index.theme"
                )
                members += ["./" + p for p in packed]
                count += len(packed)
                # Adwaita: the full theme payload + index, MINUS the postinst-only
                # binary icon-theme.cache (no gtk-update-icon-cache here).
                fn = filenames["adwaita-icon-theme"]
                deb = _download_deb(mirror, fn, cache)
                debs.append(Path(fn).name)
                packed = _pack_deb_prefix(
                    tar, deb, "usr/share/icons/Adwaita/",
                    skip=("icon-theme.cache",),
                )
                members += ["./" + p for p in packed]
                count += len(packed)
                res.icon_file_count = count
                res.icon_cache_shipped = False
                notes.append(
                    "icons: shipped index.theme + Adwaita payload; binary "
                    "icon-theme.cache omitted (gtk-update-icon-cache not on host) — "
                    "GTK falls back to a directory scan, lookups still resolve"
                )

            # --- machine-id ---------------------------------------------- #
            if "machine-id" in groups:
                _add_dir(tar, "etc")
                _add_dir(tar, "var")
                _add_dir(tar, "var/lib")
                _add_dir(tar, "var/lib/dbus")
                _add_dir(tar, "etc/dbus-1")
                for p in MACHINE_ID_PATHS:
                    _add_file(tar, p, (STUB_MACHINE_ID + "\n").encode())
                    members.append("./" + p)
                _add_file(tar, DBUS_SESSION_CONF_PATH,
                          DBUS_SESSION_CONF_BODY.encode())
                members.append("./" + DBUS_SESSION_CONF_PATH)

            # --- locale --------------------------------------------------- #
            if "locale" in groups:
                fn = filenames["libc-bin"]
                deb = _download_deb(mirror, fn, cache)
                debs.append(Path(fn).name)
                packed = _pack_deb_prefix(tar, deb, LOCALE_PREFIX)
                members += ["./" + p for p in packed]
                res.locale_file_count = len(packed)

        with tarfile.open(out_tar, "r") as t:
            res.file_count = sum(1 for m in t.getmembers() if m.isfile())
    finally:
        shutil.rmtree(work, ignore_errors=True)

    res.members = tuple(sorted(set(members)))
    res.debs = tuple(dict.fromkeys(debs))
    res.notes = tuple(notes)
    return res


