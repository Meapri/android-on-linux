"""Build the ONE-SHOT COMMON-DATA overlay (common-data-stage.tar).

Why a *class*-level overlay, not a per-app one
----------------------------------------------
The §5-E deb-closure (``tools/deb_closure.py``) follows ``DT_NEEDED`` only, so it
ships the shared libraries an app links but DROPS everything an app reads at run
time that is NOT an ELF dependency: the TLS root store, the freedesktop MIME
database, the icon-theme indices GTK probes, ``/etc/machine-id``, a usable
``$DBUS_SESSION_BUS_ADDRESS``, the compiled ``C.UTF-8`` locale. Each missing piece
shows up per-app as its own failure ("missing CA / no file types / icon lookup
stall / dbus connect refused / SIGABRT in setlocale"). Rather than patch each app,
this builder assembles ONE overlay that unblocks the data those failures share —
so a whole CLASS of GUI + network glibc apps gets what it needs in a single stage
tar.

Groups (each independently selectable; ``--all`` = every group)
---------------------------------------------------------------
``ca``        ``/etc/ssl/certs/ca-certificates.crt`` — the Mozilla CA trust bundle
              assembled from the noble ``ca-certificates`` .deb (its postinst would
              run ``update-ca-certificates``; we reproduce the default = concat all
              enabled mozilla PEMs, sorted, each newline-terminated). Unblocks TLS
              verification for chromium / curl / openssl / wget / git / python-ssl.

``mime``      ``/usr/share/mime/**`` — the freedesktop shared MIME database. The
              ``shared-mime-info`` .deb ships ONLY the source
              ``packages/freedesktop.org.xml``; the binary database
              (``mime.cache`` + ``globs2`` + ``magic`` + ``aliases`` + …) that GIO /
              GTK / Qt actually read is generated by the package's postinst via
              ``update-mime-database``. We run that host-side over the shipped XML so
              the overlay carries the COMPILED database, not just the source. Without
              it, file-type detection (``g_content_type_guess``) returns
              octet-stream for everything and "Open With" / drag-drop break.

``icons``     ``/usr/share/icons/hicolor/index.theme`` +
              ``/usr/share/icons/Adwaita/index.theme`` (+ the Adwaita theme payload).
              The ``index.theme`` is the load-bearing file: without it GTK does not
              recognise the theme AT ALL and every ``gtk_icon_theme_lookup`` misses
              (apps draw blank buttons / stall retrying the lookup). NOTE the binary
              ``icon-theme.cache`` is postinst-generated by ``gtk-update-icon-cache``
              (NOT on this host) — GTK falls back to a directory scan without it, so
              we ship the indices + payload and HONESTLY omit the binary cache (a
              perf optimisation, not a correctness gate). See HONEST SCOPE.

``machine-id````/etc/machine-id`` + ``/var/lib/dbus/machine-id`` + a session-bus
              ``/etc/dbus-1/session.conf`` stub. Many GTK/GLib apps call
              ``g_dbus_*`` / read the D-Bus machine-id at startup; a missing
              machine-id makes libdbus abort ("Unable to load
              /var/lib/dbus/machine-id"). We ship a fixed, syntactically-valid
              32-hex id (a STUB — no real per-device identity needed for a
              single-user app sandbox) so the read succeeds and the app proceeds.

``locale``    ``/usr/lib/locale/C.utf8/**`` — the COMPILED ``C.UTF-8`` locale pulled
              straight from the noble ``libc-bin`` .deb (it ships the prebuilt
              locale, unlike the source-only ``locales`` package). The base rootfs
              has NO compiled locales; an app that does ``setlocale(LC_ALL,
              "C.UTF-8")`` (most GTK apps via ``gtk_init``) then SIGABRTs. Shipping
              this 0.4 MB tree fixes that for the whole UTF-8 class. (Matches the
              WS-4 C.UTF-8 finding; staged here so it travels with the other common
              data.)

What this overlay deliberately does NOT do
------------------------------------------
* It does not weaken any sandbox or emulate a kernel-denied syscall — every member
  is a plain rootfs data file the app reads.
* It does not ship shared libraries (those are the §5-E lib closure's job); the
  only ``usr/lib`` content is the ``locale/C.utf8`` data tree.
* It is base-additive: it writes config/data paths the base rootfs lacks and never
  repoints a base SONAME (validated against ``stage_tar_spec`` — conformant).

HONEST SCOPE
------------
HOST-ONLY. ``--list`` is a network-only dry run (resolves each group's .deb
Filename, prints the planned members) and never downloads/packs. A full ``--out``
build is a NETWORK path (fetches the four data .debs). The on-device effect (apps
finding CA roots / MIME types / icons / machine-id / locale) is the
integration/device gate — the main session stages the produced tar. The
``mime.cache`` is generated by THIS host's ``update-mime-database`` if present;
when it is absent the ``mime`` group degrades to shipping the source XML only and
SAYS SO (``mime_compiled=False`` in the result) rather than silently shipping a
half database. The Adwaita/hicolor ``icon-theme.cache`` is NOT shipped (no
``gtk-update-icon-cache`` here) — GTK works without it. All offline-testable logic
(bundle assembly, tar shape, group selection) is covered by ``--selftest`` and the
pytest.
"""

