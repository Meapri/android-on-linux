def _make_synthetic_deb(tmp: Path, name: str, files: dict[str, bytes]) -> Path:
    """Build a minimal .deb (ar archive, uncompressed data.tar) for offline tests.

    Returns the .deb path or raises if ``ar`` is unavailable."""
    data_tar = tmp / "data.tar"
    with tarfile.open(data_tar, "w") as dt:
        for rel, body in files.items():
            ti = tarfile.TarInfo("./" + rel)
            ti.size = len(body)
            ti.mode = 0o644
            dt.addfile(ti, io.BytesIO(body))
    (tmp / "debian-binary").write_text("2.0\n")
    (tmp / "control.tar").write_bytes(b"")
    deb = tmp / name
    subprocess.run(
        ["ar", "qcS", deb.name, "debian-binary", "control.tar", "data.tar"],
        check=True, capture_output=True, cwd=str(tmp),
    )
    return deb


def _selftest() -> int:
    failures = 0

    def check(label: str, cond: bool) -> None:
        nonlocal failures
        if not cond:
            failures += 1
        print(f"  [{'PASS' if cond else 'FAIL'}] {label}")

    # --- group/package selection logic (pure) ------------------------------ #
    check("packages_for_groups(ca)=ca-certificates",
          packages_for_groups(["ca"]) == ["ca-certificates"])
    check("packages_for_groups(icons) pulls hicolor+adwaita",
          packages_for_groups(["icons"]) == ["hicolor-icon-theme", "adwaita-icon-theme"])
    check("packages_for_groups(machine-id) needs no deb",
          packages_for_groups(["machine-id"]) == [])
    check("packages_for_groups dedupes across groups",
          packages_for_groups(["ca", "ca"]) == ["ca-certificates"])
    check("ALL_GROUPS has the 5 documented groups",
          set(ALL_GROUPS) == {"ca", "mime", "icons", "machine-id", "locale"})

    # --- machine-id only (no network, no ar) ------------------------------- #
    with tempfile.TemporaryDirectory() as t:
        out = Path(t) / "mid.tar"
        res = build_common_data_overlay(out, ["machine-id"])
        with tarfile.open(out) as tar:
            names = {m.name: m for m in tar.getmembers()}
            bodies = {n: tar.extractfile(m).read()
                      for n, m in names.items() if m.isfile()}
        check("machine-id overlay ships ./etc/machine-id",
              "./etc/machine-id" in names)
        check("machine-id overlay ships ./var/lib/dbus/machine-id",
              "./var/lib/dbus/machine-id" in names)
        check("machine-id overlay ships ./etc/dbus-1/session.conf",
              "./etc/dbus-1/session.conf" in names)
        check("machine-id is 32-hex + newline",
              bodies.get("./etc/machine-id", b"").strip() == STUB_MACHINE_ID.encode()
              and len(STUB_MACHINE_ID) == 32)
        check("dbus session.conf is valid-ish XML busconfig",
              b"<busconfig>" in bodies.get("./etc/dbus-1/session.conf", b""))
        check("machine-id build needs no deb", res.debs == ())
        check("all members ./-rooted", all(n.startswith("./") for n in names))

    # --- ca group via injected bundle (no network) ------------------------- #
    fake = (b"-----BEGIN CERTIFICATE-----\nMIIBfake\n-----END CERTIFICATE-----\n")
    bundle = fake * 3
    with tempfile.TemporaryDirectory() as t:
        out = Path(t) / "ca.tar"
        res = build_common_data_overlay(out, ["ca"], ca_bundle=bundle)
        with tarfile.open(out) as tar:
            names = {m.name: m for m in tar.getmembers()}
            body = tar.extractfile("./" + CA_BUNDLE_PATH).read()
        check("ca overlay ships ./etc/ssl/certs/ca-certificates.crt",
              "./" + CA_BUNDLE_PATH in names)
        check("ca bundle == injected bytes", body == bundle)
        check("ca cert_count counted from injected bundle (3)",
              res.ca_cert_count == 3)

    # --- ca + machine-id combined (injected ca, no network) ---------------- #
    with tempfile.TemporaryDirectory() as t:
        out = Path(t) / "combo.tar"
        res = build_common_data_overlay(
            out, ["ca", "machine-id"], ca_bundle=bundle, ca_cert_count=3)
        with tarfile.open(out) as tar:
            names = {m.name for m in tar.getmembers()}
        check("combo overlay has both ca bundle and machine-id",
              "./" + CA_BUNDLE_PATH in names and "./etc/machine-id" in names)
        check("combo groups recorded in order", res.groups == ("ca", "machine-id"))

    # --- unknown group rejected -------------------------------------------- #
    try:
        with tempfile.TemporaryDirectory() as t:
            build_common_data_overlay(Path(t) / "x.tar", ["nope"])
        check("unknown group rejected", False)
    except ValueError:
        check("unknown group rejected", True)

    # --- assemble_ca_bundle over a synthetic ca-certificates-like .deb ------ #
    if shutil.which("ar"):
        with tempfile.TemporaryDirectory() as t:
            tmp = Path(t)
            deb = _make_synthetic_deb(tmp, "synthetic-cacerts.deb", {
                "usr/share/ca-certificates/mozilla/A.crt":
                    b"-----BEGIN CERTIFICATE-----\nAAAA\n-----END CERTIFICATE-----\n",
                "usr/share/ca-certificates/mozilla/B.crt":
                    b"-----BEGIN CERTIFICATE-----\nBBBB\n-----END CERTIFICATE-----",
                "usr/share/ca-certificates/mozilla/README": b"not a cert\n",
            })
            b2, n2 = assemble_ca_bundle(deb)
            check("assemble_ca_bundle finds 2 certs", n2 == 2)
            check("assemble_ca_bundle ignores non-cert README",
                  b"not a cert" not in b2)
            check("assemble_ca_bundle newline-terminates each cert",
                  b2.endswith(b"-----END CERTIFICATE-----\n"))
            check("assemble_ca_bundle sorts by path (A before B)",
                  b2.index(b"AAAA") < b2.index(b"BBBB"))

        # --- locale group from a synthetic libc-bin-like .deb -------------- #
        with tempfile.TemporaryDirectory() as t:
            tmp = Path(t)
            deb = _make_synthetic_deb(tmp, "synthetic-libc-bin.deb", {
                "usr/lib/locale/C.utf8/LC_CTYPE": b"CTYPE-DATA",
                "usr/lib/locale/C.utf8/LC_MESSAGES/SYS_LC_MESSAGES": b"MSG",
                "usr/bin/iconv": b"\x7fELF-unrelated",   # must NOT be packed
            })
            idx = {"libc-bin": {"Filename": "pool/x/libc-bin.deb"}}
            out = tmp / "loc.tar"
            # point the download at the local file by pre-seeding the cache name.
            cache = tmp / "cache"
            cache.mkdir()
            shutil.copy(deb, cache / "libc-bin.deb")
            res = build_common_data_overlay(
                out, ["locale"], index=idx, cache_dir=cache)
            with tarfile.open(out) as tar:
                names = {m.name for m in tar.getmembers()}
            check("locale overlay ships C.utf8/LC_CTYPE",
                  "./usr/lib/locale/C.utf8/LC_CTYPE" in names)
            check("locale overlay ships nested LC_MESSAGES file",
                  "./usr/lib/locale/C.utf8/LC_MESSAGES/SYS_LC_MESSAGES" in names)
            check("locale overlay does NOT pack unrelated usr/bin/iconv",
                  "./usr/bin/iconv" not in names)
            check("locale file_count == 2", res.locale_file_count == 2)
    else:
        check("ar available for deb-based selftests (skipped)", True)

    # --- §5-E conformance of a built overlay ------------------------------- #
    try:
        from tools.stage_tar_spec import validate_stage_tar
        with tempfile.TemporaryDirectory() as t:
            out = Path(t) / "conf.tar"
            build_common_data_overlay(
                out, ["ca", "machine-id"], ca_bundle=bundle, ca_cert_count=3)
            rep = validate_stage_tar(str(out))
            check("built overlay is stage_tar_spec conformant", rep.conformant)
    except Exception as exc:  # pragma: no cover
        check(f"stage_tar_spec cross-check ({exc!r})", False)

    print(f"\nselftest: {'ALL PASS' if failures == 0 else str(failures) + ' FAILED'}")
    return 1 if failures else 0


